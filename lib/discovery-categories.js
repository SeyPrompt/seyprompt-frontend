export function categoryImage(category) {
  return category?.image?.replace(/^https:\/\/(?:www\.)?seyprompt\.com(\/images\/categories\/)/, "$1") || `/images/categories/${category?.slug || "personal-lifestyle"}.webp`;
}

export function discoveryCategories(catalog) {
  if (!catalog || !catalog.taxonomyConfigured && !catalog.categories?.length) return discoveryFallback;
  return (catalog.categories || []).map(row => ({ ...row, description: row.description || discoveryFallback.find(fallback => fallback.slug === row.slug)?.description || "" }));
}
